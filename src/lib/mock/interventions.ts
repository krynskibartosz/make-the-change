const createWorkEntry = ({
  id,
  interventionId,
  personId,
  date,
  startTime,
  endTime,
  breakMinutes,
  days = 1,
  notes,
}: {
  id: string
  interventionId: string
  personId: string
  date: string
  startTime: string
  endTime: string
  breakMinutes: number
  days?: number
  notes?: string
}): WorkEntry => {
  const durationMinutes = calculateWorkEntryDuration({ startTime, endTime, breakMinutes, days })

  return {
    id,
    projectId: SPARRENLAAN_PROJECT_ID,
    interventionId,
    personId,
    date,
    startTime,
    endTime,
    breakMinutes,
    days,
    hourlyRate: 45,
    durationMinutes,
    amount: calculateWorkEntryAmount({ durationMinutes, hourlyRate: 45 }),
    notes,
  }
}

